/*
 * Dispatcher — the ride business logic. It owns every driver, ride and rider
 * record and decides who drives whom.
 *
 * Data structures it uses and why:
 *   HashTable<int, Driver>           drivers by id           O(1) avg lookup
 *   HashTable<int, Ride>             rides by id             O(1) avg lookup
 *   HashTable<int, LinkedList<int>>  free drivers per (area, type), so the
 *                                    nearest-driver Dijkstra can ask "is a
 *                                    free MINI parked here?" in O(1) avg
 *   HashTable<string, int>           rider -> active ride (duplicate check)
 *   HashTable<string, LinkedList<int>> rider -> history, newest first
 *   HashTable<int, int>              pending requests per area (surge demand)
 *   LinkedQueue<PendingRequest>      FIFO waiting queue with cancellation
 *   AVLTree                          leaderboard keyed by (rating, id)
 *   MinHeap<Event>                   event scheduler (shared with Simulator)
 *   Dijkstra / BFS                   routing, matching, reachability
 *
 * Every public operation records what it did into a DSTrace.
 */

struct OpResult {
    bool ok = true;
    int httpStatus = 200;
    std::string code;
    std::string message;
    int rideId = -1;

    static OpResult success(int rideId = -1, const std::string& message = "") {
        OpResult r;
        r.rideId = rideId;
        r.message = message;
        return r;
    }
    static OpResult fail(int status, const std::string& code, const std::string& message) {
        OpResult r;
        r.ok = false;
        r.httpStatus = status;
        r.code = code;
        r.message = message;
        return r;
    }
};

struct DriverPosition {
    double lat;
    double lng;
    int fromNode;
    int toNode;        // == fromNode when parked
    double progress;   // 0..1 along the current road
};

struct AreaStat {
    int area;
    int requests;
};

struct Analytics {
    int totalRides = 0;
    int completed = 0;
    int cancelled = 0;
    int active = 0;
    int waiting = 0;
    double avgWaitMin = 0.0;       // request -> pickup
    double avgFare = 0.0;
    double revenue = 0.0;
    std::vector<AreaStat> busiest; // top 5 by request count
    std::vector<int> ridesPerHour; // completed rides per sim hour
    int byType[kRideTypeCount] = {0, 0, 0};
    int topEarnerId = -1;
    double topEarnings = 0.0;
};

class Dispatcher {
public:
    static constexpr double kCarSpeedKmh = 30.0;
    static constexpr double kPickupDelayMin = 1.0;    // driver already in the pickup area
    static constexpr double kDropHandoverMin = 1.0;   // drop-off -> driver free
    static const int kMaxNameLength = 40;

    Dispatcher(CityMap& map, MinHeap<Event>& events, SimClock& clock);

    // O(D log D): wipe all state and seed `driverCount` drivers (fixed seed).
    void reset(int driverCount, unsigned seed);

    // O(log D). Adds a free driver; returns its id, or -1 for a bad area/rating.
    int addDriver(const std::string& name, RideType type, int area, int ratingCenti);

    // O((V + E) log V) for routing + matching. Valid but unmatched requests
    // go to the waiting queue (not an error).
    OpResult requestRide(const std::string& riderName, int pickup, int drop, RideType type,
                         bool autoGenerated, DSTrace& trace);

    // O(1) avg for ASSIGNED, O(q) for WAITING (queue unlink).
    OpResult cancelRide(int rideId, DSTrace& trace);

    // O(log D): AVL delete + reinsert.
    OpResult rateRide(int rideId, int stars, DSTrace& trace);

    // O(1) avg + follow-up work. Stale events (old version) are ignored.
    void handleEvent(const Event& e, DSTrace& trace);

    // O(q * (V + E) log V): retry every waiting request in FIFO order.
    void processQueue(DSTrace& trace);

    // O(A * (V + E) log V) for A active rides: re-route rides whose remaining
    // path uses `roadId`, cancel those whose destination became unreachable.
    void onRoadChanged(int roadId, DSTrace& trace);

    // O(V * (V + E))
    void recomputeSurge(DSTrace* trace);

    // ------------------------------------------------------------ queries
    // O(legs)
    DriverPosition positionOf(const Driver& d, double t) const;
    // O(1) avg
    const Ride* findRide(int id) const { return rides_.find(id); }
    const Driver* findDriver(int id) const { return drivers_.find(id); }
    // O(1) avg. nullptr if the rider has no history.
    const LinkedList<int>* historyOf(const std::string& riderName) const;
    // O(1) avg
    int freeDriversInArea(int area) const;
    int pendingInArea(int area) const;
    // O(1) avg: -1 if none
    int activeRideOf(const std::string& riderName) const;

    const HashTable<int, Driver>& drivers() const { return drivers_; }
    const HashTable<int, Ride>& rides() const { return rides_; }
    const HashTable<int, int>& activeRides() const { return activeRides_; }
    const HashTable<int, LinkedList<int>>& freeIndex() const { return freeIndex_; }
    const LinkedQueue<PendingRequest>& queue() const { return queue_; }
    const AVLTree& leaderboard() const { return leaderboard_; }
    const SurgeEngine& surge() const { return surge_; }
    const std::vector<std::string>& lastRotations() const { return lastRotations_; }

    // O(R + D + V log 5)
    Analytics analytics() const;

private:
    CityMap& map_;
    MinHeap<Event>& events_;
    SimClock& clock_;
    std::mt19937 rng_;

    HashTable<int, Driver> drivers_;
    HashTable<int, Ride> rides_;
    HashTable<int, int> activeRides_;             // ride id -> 1 (set of active ids)
    HashTable<int, LinkedList<int>> freeIndex_;   // area*3 + type -> driver ids
    HashTable<std::string, int> activeByRider_;
    HashTable<std::string, LinkedList<int>> history_;
    HashTable<int, int> pendingPerArea_;
    HashTable<int, int> requestsPerArea_;         // all-time, for analytics
    LinkedQueue<PendingRequest> queue_;
    AVLTree leaderboard_;
    SurgeEngine surge_;
    std::vector<std::string> lastRotations_;      // last AVL rotations, for the inspector
    int nextRideId_ = 1001;
    int nextDriverId_ = 1;

    static int freeKey(int area, RideType t) { return area * kRideTypeCount + (int)t; }
    static std::string riderKey(const std::string& name) { return CityMap::normalize(name); }

    double legMinutes(int roadId) const;
    void addFree(const Driver& d, DSTrace* trace);
    void removeFree(const Driver& d, DSTrace* trace);
    void startMotion(Driver& d, const PathResult& path, double start);
    void schedule(EventType type, Ride& r, double time, DSTrace& trace);
    void addPending(int area, int delta);
    int nearestNode(const Driver& d) const;
    void releaseDriver(Driver& d, DSTrace& trace);
    void finishRide(Ride& r, RideStatus status, DSTrace& trace);
    void forceCancel(Ride& r, const std::string& reason, DSTrace& trace);
    void applyRating(Driver& d, int stars, DSTrace& trace);
    bool tryAssign(Ride& r, DSTrace& trace);
    void assignDriver(Ride& r, Driver& d, const PathResult& driverToPickup, DSTrace& trace);
    void reroute(Ride& r, Driver& d, DSTrace& trace);
    void onArrivedPickup(Ride& r, DSTrace& trace);
    void onRideCompleted(Ride& r, DSTrace& trace);
    void onDriverFree(Ride& r, DSTrace& trace);
};
