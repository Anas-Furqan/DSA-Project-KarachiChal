const int RIDE_TYPE_COUNT = 3;
const int MAX_DRIVERS = 100;

enum class RideType { BIKE, MINI, AC };
enum class DriverStatus { AVAILABLE, TO_PICKUP, ON_TRIP };
enum class RideStatus { WAITING, ASSIGNED, IN_PROGRESS, COMPLETED, CANCELLED };
enum class EventType { DRIVER_ARRIVED_PICKUP, RIDE_COMPLETED, DRIVER_FREE };

string rideTypeName(RideType t);
bool parseRideType(string text, RideType& out);
string driverStatusName(DriverStatus s);
string rideStatusName(RideStatus s);
string eventTypeName(EventType e);
int computeFare(RideType t, double km, double surge);
string freeKey(int area, RideType t);

// Leg i goes nodes[i] -> nodes[i+1] between legStart[i] and legEnd[i] (sim minutes).
struct Motion {
    int nodes[MAX_ROUTE];
    int roads[MAX_ROUTE];
    double legStart[MAX_ROUTE];
    double legEnd[MAX_ROUTE];
    int legCount;

    bool active() const;
    double endTime() const;
    int legAt(double t) const;
    void clear();
};

struct Driver {
    int id;
    string name;
    RideType type;
    double ratingSum;
    int ratingCount;
    int rating;
    int areaId;
    DriverStatus status;
    int rideId;
    Motion motion;
    double earnings;
    int tripsCompleted;
};

struct Ride {
    int id;
    string riderName;
    int pickup;
    int drop;
    RideType type;
    RideStatus status;
    int driverId;
    double distanceKm;
    double surge;
    int fare;
    double requestTime;
    double assignTime;
    double pickupTime;
    double completeTime;
    double endTime;
    double etaPickup;
    int tripNodes[MAX_ROUTE];
    int tripCount;
    string cancelReason;
    int rating;
    bool autoGenerated;
    int eventVersion;
};

struct Rider {
    string name;
    int activeRideId;
    LinkedList history;
};

